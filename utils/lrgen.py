#!/usr/bin/env python3
# LR tables from bison --xml, for the Erlang engine (candyspeak_parse.erl).
#
# usage: lrgen.py candyspeak.y candyspeak.xml candyspeak_parse_tab.erl
#
# candyspeak.y gives what the XML does not: each rule's action NAME (the `{ name }'
# after it) and each token's spelling, the lexer's category. Bison numbers
# its rules in the order they are written, rule 0 being its own $accept;
# the names are taken in the same order. Actions are numbered 0..255 in
# the order they first appear (act_names/0), for C to switch on.
import re
import sys
import xml.etree.ElementTree as ET


def grammar(yfile):
    text = open(yfile).read()
    head, body = text.split('\n%%\n', 1)
    spell = {}
    toks = re.findall(r'^%token\s+(\w+)\s+"([^"]*)"', head, re.M)
    for name, sp in toks:
        spell[name] = sp
        spell['"%s"' % sp] = sp
    acts = re.findall(r'\{\s*(\w+)\s*\}', body)
    return spell, acts, [sp for _, sp in toks]


def erl_atom(s):
    if re.match(r'^[a-z][A-Za-z0-9_@]*$', s) and s not in RESERVED:
        return s
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


RESERVED = {'after', 'and', 'andalso', 'band', 'begin', 'bnot', 'bor', 'bsl',
            'bsr', 'bxor', 'case', 'catch', 'cond', 'div', 'end', 'fun', 'if',
            'let', 'not', 'of', 'or', 'orelse', 'receive', 'rem', 'try',
            'when', 'xor', 'maybe', 'else'}


def main():
    yfile, xfile, out = sys.argv[1:4]
    spell, acts, toks = grammar(yfile)
    r = ET.parse(xfile).getroot()
    g = r.find('grammar')
    rules = {}
    for ru in g.find('rules'):
        n = int(ru.get('number'))
        lhs = ru.find('lhs').text
        rhs = ru.find('rhs').findall('symbol')
        rules[n] = (lhs, len(rhs))
    assert len(rules) - 1 == len(acts), (len(rules), len(acts))
    order = []
    for a in acts:
        if a not in order:
            order.append(a)
    assert len(order) <= 256

    def cat(sym):
        if sym == '$end':
            return "'$end'"
        return erl_atom(spell[sym])

    w = []
    w.append('%% generated by lrgen.py from candyspeak.y -- do not edit\n'
             '-module(candyspeak_parse_tab).\n'
             '-export([action/2, goto/2, rule/1, act_names/0, tokens/0]).\n\n')
    acl = []
    gol = []
    for s in r.find('automaton').findall('state'):
        n = int(s.get('number'))
        a = s.find('actions')
        dflt = None
        for t in a.find('transitions'):
            sym, to = t.get('symbol'), int(t.get('state'))
            if t.get('type') == 'shift':
                acl.append('action(%d, %s) -> {shift, %d};\n' % (n, cat(sym), to))
            else:
                gol.append('goto(%d, %s) -> %d;\n' % (n, erl_atom(sym), to))
        for x in a.find('reductions'):
            if x.get('enabled') != 'true':
                continue
            rule = x.get('rule')
            v = 'accept' if rule == 'accept' else '{reduce, %s}' % rule
            if x.get('symbol') == '$default':
                dflt = v
            else:
                acl.append('action(%d, %s) -> %s;\n' % (n, cat(x.get('symbol')), v))
        if dflt:
            acl.append('action(%d, _) -> %s;\n' % (n, dflt))
    w += acl
    w.append('action(_, _) -> error.\n\n')
    w += gol
    w.append('goto(S, Nt) -> erlang:error({no_goto, S, Nt}).\n\n')
    for n in sorted(rules):
        if n == 0:
            continue
        lhs, ln = rules[n]
        w.append('rule(%d) -> {%s, %d, %s};\n' % (n, erl_atom(lhs), ln,
                                                 erl_atom(acts[n - 1])))
    w.append('rule(R) -> erlang:error({no_rule, R}).\n\n')
    w.append('%% the actions by number, 0..255: what C switches on\n')
    w.append('act_names() ->\n    [%s].\n' % ',\n     '.join(erl_atom(a) for a in order))
    w.append('\n%% the token categories in candyspeak.y\'s %token order: code 1, 2 ...\n')
    w.append('tokens() ->\n    [%s].\n' % ',\n     '.join(erl_atom(sp) for sp in toks))
    open(out, 'w').write(''.join(w))
    print('rules %d actions %d' % (len(rules) - 1, len(order)))


main()
