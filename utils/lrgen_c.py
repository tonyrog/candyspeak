#!/usr/bin/env python3
# C tables from bison --xml for candyspeak.y: lrpack.py's compact 8-bit
# encoding (level 4), its reduce classes carrying the action number.
#
# usage: lrgen_c.py candyspeak.y candyspeak.xml outdir
#
# Writes outdir/csp_lr_tab.h (the tables), csp_lr_act.h (A_<name> 0..255, as
# candyspeak_parse_tab:act_names/0 numbers them), csp_lr_act.def and
# csp_lr_tokens.def (X(NAME, "spelling"), the token codes 1.. in
# candyspeak.y's %token order, 0 the end).
import collections
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lrpack as gen  # noqa: E402

LEVEL = 4


def grammar(yfile):
    text = open(yfile).read()
    head, body = text.split('\n%%\n', 1)
    toks = re.findall(r'^%token\s+(\w+)\s+"([^"]*)"', head, re.M)
    acts = re.findall(r'\{\s*(\w+)\s*\}', body)
    return toks, acts


def load(xfile, toks):
    r = ET.parse(xfile).getroot()
    g = r.find('grammar')
    tcode = {'$end': 0}
    for i, (name, sp) in enumerate(toks):
        tcode[name] = i + 1
        tcode['"%s"' % sp] = i + 1
    rules = {}
    for ru in g.find('rules'):
        rules[int(ru.get('number'))] = (ru.find('lhs').text,
                                        len(ru.find('rhs').findall('symbol')))
    nts = [nt.get('name') for nt in g.find('nonterminals')]
    states = {}
    for s in r.find('automaton').findall('state'):
        a = s.find('actions')
        tr = [(t.get('type'), t.get('symbol'), int(t.get('state')))
              for t in a.find('transitions')]
        rd = [(x.get('symbol'), x.get('rule')) for x in a.find('reductions')
              if x.get('enabled') == 'true']
        # a lookahead reduction by the default's own rule is the default
        d = [rule for sym, rule in rd if sym == '$default']
        rd = [(sym, rule) for sym, rule in rd
              if sym == '$default' or not d or rule != d[0]]
        states[int(s.get('number'))] = (tr, rd)
    return tcode, rules, nts, states


def main():
    yfile, xfile, out = sys.argv[1:4]
    toks, acts = grammar(yfile)
    assert len(toks) < 128, 'a token code has 7 bits'
    order = []
    for a in acts:
        if a not in order:
            order.append(a)
    assert len(order) <= 256
    anum = {a: i for i, a in enumerate(order)}
    tcode, rules, nts, states = load(xfile, toks)
    assert len(rules) - 1 == len(acts)
    action_of = lambda r: anum[acts[r - 1]] if r > 0 else 0
    real, rows, gotos, ctab, accept, ngr = gen.build(LEVEL, tcode, rules, nts,
                                                     states, action_of)
    rbytes, soff, uniq, parent, roffs = gen.encode_rows(LEVEL, rows)
    ns = len(real)
    # a goto target is a state or a goto-reduce class (NSTATES + class):
    # 16 bits, as the two do not fit 8 together
    assert ns <= 255 and len(ctab) <= 255, (ns, len(ctab))
    pidx = sorted({p for p in parent if p is not None})
    pslot = {p: i for i, p in enumerate(pidx)}
    for i in range(len(uniq)):
        if parent[i] is not None:
            rbytes[roffs[i] + 2] = pslot[parent[i]]
    gbytes, goff = [], []
    for nt, lst in gotos.items():
        goff.append(len(gbytes))
        cnt = collections.Counter(t for _, t in lst)
        d = cnt.most_common(1)[0][0] if lst else 0
        ex = [(f, t) for f, t in lst if t != d]
        gbytes += [len(ex), d & 255, d >> 8]
        for f, t in ex:
            gbytes += [f, t & 255, t >> 8]
    ntidx = {nt: i for i, nt in enumerate(gotos)}
    lhs = [ntidx.get(l, 0) for l, _, _ in ctab]
    ln = [n for _, n, _ in ctab]
    act = [a for _, _, a in ctab]

    with open(os.path.join(out, 'csp_lr_tab.h'), 'w') as f:
        w = f.write
        w('// generated by lrgen_c.py from candyspeak.y -- do not edit\n')
        w('#define LR_NSTATES %d\n#define LR_NCLASS %d\n' % (ns, len(ctab)))
        w('#define LR_PARENT 1\n#define LR_ACCEPT %d\n' % accept)

        def arr(t, name, data):
            w('static const %s %s[] RO = {' % (t, name))
            for i, v in enumerate(data):
                w(('\n    ' if i % 12 == 0 else ' ') + '%d,' % v)
            w('\n};\n')
        arr('uint8_t', 'lr_rows', rbytes)
        arr('uint16_t', 'lr_row_off', soff)
        arr('uint16_t', 'lr_parent_off', [roffs[p] for p in pidx])
        arr('uint8_t', 'lr_gotos', gbytes)
        arr('uint16_t', 'lr_goto_off', goff)
        arr('uint8_t', 'lr_lhs', lhs)
        arr('uint8_t', 'lr_len', ln)
        arr('uint8_t', 'lr_act', act)
    with open(os.path.join(out, 'csp_lr_act.h'), 'w') as f:
        f.write('// generated by lrgen_c.py from candyspeak.y -- do not edit\n'
                '// the actions of candyspeak.y, numbered as they first appear\n'
                'enum {\n')
        for a in order:
            f.write('    A_%s,\n' % a)
        f.write('    A_COUNT\n};\n')
    with open(os.path.join(out, 'csp_lr_act.def'), 'w') as f:
        for a in order:
            f.write('A(%s)\n' % a)
    with open(os.path.join(out, 'csp_lr_tokens.def'), 'w') as f:
        for name, sp in toks:
            f.write('X(%s, "%s")\n' % (name, sp))
    size = len(rbytes) + 2 * ns + 2 * len(pidx) + len(gbytes) + 2 * len(goff) + 3 * len(ctab)
    print('states %d classes %d actions %d tables %d B' % (ns, len(ctab), len(order), size))


main()
